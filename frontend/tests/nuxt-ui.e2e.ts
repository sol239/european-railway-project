import { test, expect } from '@playwright/test'

test('Nuxt UI controls preserve station details, map settings, timeline and mobile layout', async ({ page }) => {
  test.setTimeout(90000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/api/stations*', route => route.fulfill({ json: { stations: [{ key: 1, name: 'strasbourg', latitude: 47, longitude: 2, visits: 12 }], coverage: { firstDate: '2026-11-12', lastDate: '2027-04-30' } } }))
  await page.route('**/api/railways', route => route.fulfill({ json: { type: 'FeatureCollection', features: [{ type: 'Feature', id: 'test', properties: { mnemo: 'EXPLOITE' }, geometry: { type: 'LineString', coordinates: [[2, 47], [4, 47]] } }], metadata: {} } }))
  await page.route('**/api/trains?**', route => route.fulfill({ json: { trains: [{ id: 'test', name: 'Express', stops: [{ station: 1, name: 'Alpha', longitude: 2, latitude: 47, arrival: 0, departure: 0 }, { station: 2, name: 'Beta', longitude: 4, latitude: 47, arrival: 86399, departure: 86399 }] }] } }))
  await page.goto('/')
  await expect(page.getByTestId('station-map')).toHaveAttribute('data-ready', 'true', { timeout: 45000 })
  await expect(page.getByRole('searchbox', { name: 'Find a station' })).toHaveCount(0)
  await expect(page.getByText('mapped stations', { exact: true })).toHaveCount(0)
  await page.locator('.station-row').first().click()
  await expect(page.getByTestId('selected-station')).toBeVisible()
  await expect(page.getByText('SELECTED STATION', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Map settings', exact: true }).click()
  const modal = page.getByRole('dialog', { name: 'Map settings' })
  await expect(modal).toBeVisible()
  await modal.getByRole('combobox', { name: 'Map theme' }).click()
  await page.getByRole('option', { name: 'Neon', exact: true }).click()
  await modal.getByRole('combobox', { name: 'Map view' }).click()
  await page.getByRole('option', { name: '3D', exact: true }).click()
  await modal.getByRole('combobox', { name: 'Map view' }).click()
  await page.getByRole('option', { name: '2D', exact: true }).click()
  await modal.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(modal).not.toBeVisible()
  await page.getByRole('combobox', { name: 'Railway lines' }).click()
  await page.getByRole('option', { name: 'Off', exact: true }).click()
  const slider = page.getByRole('slider', { name: 'Timeline time' })
  await slider.focus()
  await page.keyboard.press('Home')
  await page.keyboard.press('ArrowRight')
  await expect(slider).toHaveAttribute('aria-valuenow', '1')
  await page.getByRole('button', { name: 'Now', exact: true }).click()
  await page.screenshot({ path: '/tmp/railway-nuxt-ui-desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Map settings', exact: true }).click()
  await expect(modal).toBeVisible()
  await expect(modal).toHaveCSS('opacity', '1')
  await expect(modal).toHaveCSS('background-color', 'rgb(16, 29, 48)')
  await expect(modal.getByRole('button', { name: 'Done', exact: true })).toHaveCSS('color', 'rgb(16, 29, 48)')
  await page.screenshot({ path: '/tmp/railway-nuxt-ui-mobile.png', animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
