import { expect, test, type Page } from '@playwright/test'

async function selectOption(page: Page, label: string, option: string) {
  await page.getByRole('combobox', { name: label, exact: true }).click()
  await page.getByRole('option', { name: option, exact: true }).click()
}

test('serves real Gold station data and rejects malformed date filters', async ({ request }) => {
  const response = await request.get('/api/stations')
  expect(response.ok()).toBeTruthy()
  const body = await response.json()
  const station = body.stations.find((station: { key: number }) => station.key === 543)
  expect(station.name).toBe('strasbourg')
  expect(station.latitude).toBeCloseTo(48.58511)
  expect(station.longitude).toBeCloseTo(7.733882)
  expect(body.stations.length).toBeGreaterThan(3000)
  expect((await request.get('/api/stations?date=2026-02-30')).status()).toBe(400)
})

test('renders Cesium, opens station details, and switches perspective', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('complementary', { name: 'Station explorer' })).toBeVisible()
  await expect(page.getByTestId('station-map')).toHaveAttribute('data-ready', 'true', { timeout: 45_000 })
  await expect(page.locator('.station-row').first()).toBeVisible()
  await page.screenshot({ path: '/tmp/railway-atlas-desktop.png', fullPage: true })
  await expect(page.locator('.station-row').first()).toBeVisible()
  await page.locator('.station-row').filter({ has: page.locator('strong', { hasText: /^strasbourg$/ }) }).click()
  await expect(page.getByTestId('selected-station')).toContainText('48.58511')
  await expect(page.getByTestId('selected-station')).toContainText('7.73388')
  await page.getByRole('button', { name: 'Map settings', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Map settings' })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Map view' })).toContainText('2D')
  await selectOption(page, 'Map view', '3D')
  await expect(page.getByRole('combobox', { name: 'Map view' })).toContainText('3D')
  await selectOption(page, 'Map view', '2D')
  const resolution = page.getByRole('combobox', { name: 'Map resolution' })
  await expect(resolution).toContainText('1×')
  const initialCanvasScale = await page.locator('.cesium-host canvas').evaluate((canvas: HTMLCanvasElement) => canvas.width / canvas.clientWidth)
  for (const scale of ['0.5', '0.75', '1.5', '3', '1']) {
    await selectOption(page, 'Map resolution', scale + '×')
    await expect.poll(() => page.locator('.cesium-host canvas').evaluate((canvas: HTMLCanvasElement) => canvas.width / canvas.clientWidth)).toBeCloseTo(initialCanvasScale, 2)
  }
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Map settings' })).not.toBeVisible()
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  expect(errors).toEqual([])
})

test('keeps the map and station explorer accessible on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByTestId('station-map')).toHaveAttribute('data-ready', 'true', { timeout: 45_000 })
  await expect(page.getByRole('button', { name: 'Zoom in', exact: true })).toBeVisible()
  await expect(page.locator('.station-row').first()).toBeAttached()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '/tmp/railway-atlas-mobile.png', fullPage: true })
})

test('displays RFN railway lines and filters operating infrastructure', async ({ page, request }) => {
  const response = await request.get('/api/railways')
  expect(response.ok()).toBeTruthy()
  const collection = await response.json()
  expect(collection.type).toBe('FeatureCollection')
  expect(collection.features.length).toBeGreaterThan(1000)
  expect(collection.metadata.operatingSegments).toBeGreaterThan(0)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const map = page.getByTestId('station-map')
  await expect(map).toHaveAttribute('data-ready', 'true', { timeout: 45_000 })
  const layer = page.getByRole('combobox', { name: 'Railway lines' })
  await expect(layer).toContainText('Operating')
  await selectOption(page, 'Railway lines', 'Operating')
  await expect(map).toHaveAttribute('data-railways-ready', 'true', { timeout: 45_000 })
  await expect(map).toHaveAttribute('data-railway-segments', String(collection.metadata.operatingSegments))
  await expect(page.locator('.railways-notice')).not.toBeVisible()
  await page.screenshot({ path: '/tmp/railway-rfn-layer.png' })
  await selectOption(page, 'Railway lines', 'All statuses')
  await expect(map).toHaveAttribute('data-railway-segments', String(collection.metadata.segments))
  await page.getByRole('button', { name: 'Map settings', exact: true }).click()
  await selectOption(page, 'Map view', '3D')
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(map).toHaveAttribute('data-railway-segments', String(collection.metadata.segments))
  await selectOption(page, 'Railway lines', 'Off')
  await expect(map).toHaveAttribute('data-railway-segments', '0')
  expect(errors).toEqual([])
})
